-- Дата релиза — календарная дата, хранится как полдень UTC этого дня.
-- Раньше импорт с ЯМ («2019-03-15T00:00:00+03:00») сохранял 2019-03-14 21:00 UTC,
-- и форма/вывод показывали день раньше. Приводим существующие значения к
-- календарной дате по Москве (для ручного ввода — полночь UTC — и для iTunes —
-- утро UTC — московская дата совпадает с введённой), в полдень UTC.
-- Идемпотентно: значения, уже стоящие в 12:00:00, не трогаем.
UPDATE "Release"
   SET "releaseDate" = (("releaseDate" AT TIME ZONE 'UTC') AT TIME ZONE 'Europe/Moscow')::date + TIME '12:00'
 WHERE "releaseDate" IS NOT NULL
   AND "releaseDate"::time <> TIME '12:00';
